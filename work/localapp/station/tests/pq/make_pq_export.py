#!/usr/bin/env python3
"""Synthetic ProQuest multi-article EXPORTS for the PQEXPORT-v1 tests (no real multi-article export has been seen). Each article is drawn in the layout of the real single-article
PDFs: heading (wrapped, one hyphenated), "Last, First . Last, First." line, "ProQuest document link", "FULL TEXT", the text, DETAILS (label column, value column, "Publication history :",
footer inside the block), Document URL wrapped over 3 lines, "LINKS", "Check for Full Text", "Database copyright ... ProQuest LLC". The footer "PDF GENERATED BY PROQUEST.COM Page x of N" counts the whole file.

    python3 -I make_pq_export.py OUTDIR            writes exp_1, exp_2, exp_6, exp_60 (.pdf) , exp_6_contents, exp_6_broken, exp_6_nomarks, exp_3_newpage and expected.json
Importable: make(path, n, markers=True, contents=False, broken=(), newpage=False)."""
import json, sys, os, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_pq_pdfs as M

OUTLETS = [('Food Processing; Chicago', 'Food Processing'), ('Fresno Test Gazette; Fresno, Calif.', 'Fresno Test Gazette'), ('Valley Ledger Test; Van Nuys, Calif.', 'Valley Ledger Test'), ('Capitol Weekly Test; Sacramento', 'Capitol Weekly Test')]
FIRST = ['Dave', 'Dana', 'Marta', 'Chris', 'Priya', 'Omar', 'Lena', 'Tom']; LAST = ['Fusaro', 'Whitfield', 'Lopez', 'Hart', 'Nair', 'Haddad', 'Berg', 'Quill']
STEM = ['Assemblymember Gabriel', 'A new California bill', 'State lawmakers', 'California may create', 'Lawmakers weigh', 'Committee backs', 'Gabriel says', 'Budget panel hears']

def art(i, seed=1):
    r = random.Random(seed * 1000 + i)
    pub, outlet = OUTLETS[i % len(OUTLETS)]
    day = 1 + (i % 27); mon = 1 + (i // 27) % 12
    hl = f'{STEM[i % len(STEM)]} {M.lorem(5 + i % 3, 300 + i + 50 * seed, mention=False).lower()}'.strip().rstrip('.')
    if i % 5 == 0: hl = hl.replace(' ', ' Non-' + 'UPF ', 1) if False else hl + ' for Non-UPF Foods'
    a1 = (FIRST[i % 8], LAST[(i * 3) % 8]); a2 = (FIRST[(i + 3) % 8], LAST[(i + 5) % 8])
    auth = f'{a1[1]}, {a1[0]}' + (f'; {a2[1]}, {a2[0]}' if i % 4 == 0 else '')
    return dict(i=i, hl=hl, pub=pub, outlet=outlet, date=f'2026-{mon:02d}-{day:02d}', mdy=f'{M.MON3[mon-1]} {day}, 2026', auth=auth,
                docid=str(3400000000 + 1000 * seed + i), by=(f'{a1[0]} {a1[1]}' + (f' and {a2[0]} {a2[1]}' if i % 4 == 0 else '')), body=M.lorem(110 + (i * 37) % 260, 600 + i + seed))

def draw(path, arts, hint, markers, contents, broken, newpage):
    p = M.Pen(path, hint)
    if contents:
        p.line(f'Documents ({len(arts)})', 'DJB', 14, 22)
        for k, a in enumerate(arts, 1):
            p.line(f'{k}. {a["hl"]}'[:100], 'DJ', 9, 13); p.line(f'{a["pub"]}, {a["mdy"]}'[:100], 'DJ', 8, 12)
        p.newpage()
    n = len(arts)
    for k, a in enumerate(arts, 1):
        if k > 1 and newpage: p.newpage()
        elif k > 1: p.gap(18)
        p.room(150)
        if markers: p.line(f'Document {k} of {n}', 'DJB', 10, 16)
        for ln in p.wrap(a['hl'], 'DJB', 14, 400): p.line(ln, 'DJB', 14, 18)
        p.line(f'{a["auth"]} . {a["auth"]}.', 'DJ', 10, 15); p.line('ProQuest document link', 'DJ', 10, 14); p.gap(8); p.line('FULL TEXT', 'DJB', 10, 16)
        p.para(a['body'], 'DJ', 10, 13); p.gap(10)
        p.room(260)
        p.line('DETAILS', 'DJB', 11, 18)
        L = lambda lab, v: p.line(f'{lab}'.ljust(30) + v, 'DJ', 9, 15)
        if k in broken:   # a garbled details block: the labels are gone
            p.line('Publication details could not be exported for this document.', 'DJ', 9, 15); p.line(f'ID {a["docid"]}', 'DJ', 9, 15)
        else:
            L('Subject:', 'Public health; Processed foods; Consumers'); L('Location:', 'California; United States--US'); L('Publication title:', a['pub']); L('Publication year:', '2026'); L('Publication date:', a['mdy'])
            L('Publisher:', 'Test Media'); L('Place of publication:', a['pub'].split(';')[1].strip() if ';' in a['pub'] else ''); L('ISSN:', '00156523'); L('Source type:', 'Trade Journal'); L('Language of publication:', 'English'); L('Document type:', 'News')
            p.line('Publication history :', 'DJ', 9, 15); L('Online publication date:', '2026-03-26')
            L('ProQuest document ID:', a['docid'])
            L('Document URL:', f'https://castatelib.idm.oclc.org/login?url=https://www.proquest.com/trade-'); p.line(' ' * 30 + f'journals/some-slug-{k}/docview/{a["docid"]}/se-', 'DJ', 9, 15); p.line(' ' * 30 + '2?accountid=26958', 'DJ', 9, 15)
            L('Copyright:', 'Copyright Test Media 2026'); L('Last updated:', '2026-08-14'); L('Database:', 'SciTech Premium Collection')
        p.gap(6); p.line('LINKS', 'DJB', 11, 18); p.line('Check for Full Text', 'DJ', 9, 14); p.gap(6); p.line('Database copyright  2026 ProQuest LLC. All rights reserved.', 'DJ', 8, 14)
    return p.end()

def make(path, n, markers=True, contents=False, broken=(), newpage=False, seed=1):
    arts = [art(i, seed) for i in range(1, n + 1)]
    hint = draw(path, arts, 1, markers, contents, set(broken), newpage)
    draw(path, arts, hint, markers, contents, set(broken), newpage)
    return arts

if __name__ == '__main__':
    out = sys.argv[1]; os.makedirs(out, exist_ok=True); exp = {}
    for name, kw in {'exp_1': dict(n=1), 'exp_2': dict(n=2, seed=2), 'exp_6': dict(n=6), 'exp_60': dict(n=60, seed=4), 'exp_6_contents': dict(n=6, contents=True, seed=3), 'exp_6_broken': dict(n=6, broken=(3,)),
                     'exp_6_nomarks': dict(n=6, markers=False), 'exp_3_newpage': dict(n=3, newpage=True), 'exp_5_contents_nomarks': dict(n=5, contents=True, markers=False)}.items():
        exp[name] = dict(kw=dict(kw), arts=make(os.path.join(out, name + '.pdf'), **kw))
    json.dump(exp, open(os.path.join(out, 'expected.json'), 'w'), indent=1); print('wrote', len(exp))
