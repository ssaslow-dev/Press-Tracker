def lorem(n, seed, mention=True):
    rnd = random.Random(5000 + seed); out = []
    while len(out) < n:
        k = rnd.randint(8, 16); sent = [rnd.choice(VOCAB) for _ in range(k)]
        sent[0] = sent[0].capitalize(); out.append(' '.join(sent) + '.')
    t = ' '.join(' '.join(out).split(' ')[:n])
    return ('"We have to get this done," said Assemblymember Jesse Gabriel (D-Encino), who chairs the committee. ' + t) if mention else t


class Pen:
    def __init__(self, path, npages_hint=1, furniture=True):
        self.c = canvas.Canvas(path, pagesize=letter, pageCompression=0); self.c.setTitle('ProQuest document')
        self.y = H - TOP; self.page = 1; self.furniture = furniture; self.hint = npages_hint; self.bodyfont = 'DJ'

    def foot(self):
        if not self.furniture: return
        self.c.setFont('DJ', 8); self.c.drawString(LM, 34, 'PDF GENERATED BY PROQUEST.COM'); self.c.drawRightString(W - RM, 34, f'Page {self.page} of {self.hint}')

    def newpage(self):
        self.foot(); self.c.showPage(); self.page += 1; self.y = H - TOP

    def room(self, h):
        if self.y - h < BOT: self.newpage()

    def wrap(self, text, font, size, width):
        if font in ('DJ', 'DJB') and any(ord(ch) > 0x2E80 for ch in text): font = 'WQY'
        words = []
        for w in text.split(' '):
            while pdfmetrics.stringWidth(w, font, size) > width:
                k = len(w)
                while pdfmetrics.stringWidth(w[:k], font, size) > width: k -= 1
                words.append(w[:k]); w = w[k:]
            words.append(w)
        lines, cur = [], ''
        for w in words:
            t = (cur + ' ' + w).strip()
            if pdfmetrics.stringWidth(t, font, size) <= width or not cur: cur = t
            else: lines.append(cur); cur = w
        if cur: lines.append(cur)
        return lines

    def line(self, text, font='DJ', size=10, lead=13):
        if font in ('DJ', 'DJB') and any(ord(ch) > 0x2E80 for ch in text): font = 'WQY'
        self.room(lead); self.c.setFont(font, size); self.c.drawString(LM, self.y - size, text); self.y -= lead

    def para(self, text, font='DJ', size=10, lead=13, width=None):
        for ln in self.wrap(text, font, size, width or (W - LM - RM)): self.line(ln, font, size, lead)

    def gap(self, h): self.y -= h

    def end(self):
        self.foot(); self.c.showPage(); self.c.save(); return self.page


def mdy(d): return f'{MON3[d[1]-1]} {d[2]}, {d[0]}'
def dmy(d): return f'{d[2]} {MON3[d[1]-1]} {d[0]}'


def details(s, drop=()):
    """the labelled lines, in ProQuest's order; `drop` removes labels (a PDF whose block lacks some)"""
    docid = s.get('docid', '')
    rows = [('Title', s['hl']), ('Author', s.get('au_pq', '')), ('Publication title', s['pub']), ('Publication year', str(s['d'][0])),
            ('Publication date', s.get('pubdate') or mdy(s['d'])), ('Section', s.get('sec', '')), ('Pages', s.get('pg', '')), ('Publisher', s.get('publisher', '')),
            ('Place of publication', s.get('place', '')), ('Country of publication', 'United States'), ('ISSN', s.get('issn', '')), ('Source type', s.get('stype', 'Newspapers')),
            ('Language of publication', s.get('lang', 'English')), ('Document type', s.get('dtype', 'News')), ('ProQuest document ID', docid),
            ('Document URL', f'https://www.proquest.com/docview/{docid}/{hashlib.sha1(docid.encode()).hexdigest()[:20].upper()}/1?accountid=13802' if docid else ''),
            ('Copyright', s.get('copyright', f'Copyright {s["d"][0]} {s["pub"].split(";")[0]}')), ('Last updated', f'{s["d"][0]}-{s["d"][1]:02d}-{s["d"][2]:02d}'),
            ('Database', s.get('db', 'ProQuest Central'))]
    return [(k, v) for k, v in rows if v and k not in drop]


def make(path, s):
    """s: dict(hl, d, pub, au_pq, docid, n, layout, pages_hint, lang, zh, drop (labels), noheading ...)"""
    p = Pen(path, s.get('pages_hint', 1), furniture=s.get('furniture', True))
    zh = s.get('zh'); bf = 'WQY' if zh else 'DJ'; tf = 'WQY' if zh else 'DJB'
    body = lorem(s['n'], zlib.crc32(s['hl'].encode()), s.get('mention', True))
    if zh: body = '加州众议员杰西·加布里埃尔（Jesse Gabriel）周二在萨克拉门托表示，预算委员会将审议住房和野火恢复的开支。' * s.get('zhrep', 3)
    if s.get('es'): body = ('El asambleísta Jesse Gabriel (D-Encino) presentó el martes en Sacramento una ley para acelerar la construcción de viviendas asequibles en el Valle de San Fernando. ' + ' '.join(['Los vecinos y los líderes comunitarios dijeron que la medida ayudará a las familias que buscan casa.'] * s.get('esrep', 6)))
    cut = len(body) // 2; cut = body.find(' ', cut) if not zh else cut
    paras = [body[:cut].strip(), body[cut:].strip()]
    if s.get('layout', 'A') == 'A':
        if not s.get('noheading'):
            p.para(s['hl'], tf, 16, 20, width=W - LM - RM)
            p.gap(4)
            if s.get('citation', True): p.para(f'{s.get("au_pq", "")}. {s["pub"]}. {dmy(s["d"])}.'.lstrip('. '), 'DJ', 10, 13)
            p.line('ProQuest document link', 'DJ', 10, 13); p.gap(6)
            p.line('FULL TEXT', 'DJB', 10, 14)
        for para in paras:
            for _ in range(s.get('rep', 1)):
                p.para(para, bf, 10, 13); p.gap(8)
        if s.get('extra_pages'):
            for k in range(s['extra_pages']):
                p.para(lorem(260, zlib.crc32(s['hl'].encode()) + k + 1, mention=False), bf, 10, 13); p.gap(8)
        p.gap(6); p.line('Details', 'DJB', 11, 16)
        for k, v in details(s, s.get('drop', ())):
            if k in ('Subject',): continue
            for i, ln in enumerate(p.wrap(f'{k}: {v}', 'DJ', 9, W - LM - RM)): p.line(ln, 'DJ', 9, 12)
    else:   # B: labelled block first
        p.para('Document View', 'DJB', 11, 14); p.gap(4)
        for k, v in details(s, s.get('drop', ())):
            for ln in p.wrap(f'{k}: {v}', 'DJ', 9, W - LM - RM): p.line(ln, 'DJ', 9, 12)
        p.gap(10); p.line('Full text', 'DJB', 10, 14)
        if not s.get('noheading'): p.para(s['hl'], tf, 14, 18); p.gap(4)
        for para in paras:
            p.para(para, bf, 10, 13); p.gap(8)
    return p.end()


